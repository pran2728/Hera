// Builds the single-file Edge Functions pasted into Supabase:
//   backend/hera-chat.ts   from backend/hera-chat.template.ts  + cycle engine
//   backend/hera-nudge.ts  from backend/hera-nudge.template.ts + cycle engine + nudge rules
// so the app, the functions and the tests all share one copy of the logic.
import { readFileSync, writeFileSync } from 'node:fs'

const strip = file => readFileSync(file, 'utf8')
  .replace(/^import .*\n/gm, '')
  .replace(/^export \{[^}]*\}\n?/gm, '')
  .replace(/^export /gm, '')
  .replace(/^\/\/.*\n/gm, '')

function build(name, marker, modules) {
  const template = readFileSync(`backend/${name}.template.ts`, 'utf8')
  const shared = modules.map(m => `// ---- copied from ${m} ----\n${strip(m)}`).join('\n')
  const out = '// @ts-nocheck\n' + template
    .replace(`// GENERATED FILE SOURCE: edit backend/${name}.template.ts, then run \`npm run build:function\`.\n`,
             `// Built from backend/${name}.template.ts. Do not edit this file directly.\n`)
    .replace(marker, shared)
  writeFileSync(`backend/${name}.ts`, out)
  console.log(`backend/${name}.ts written (${out.split('\n').length} lines)`)
}

build('hera-chat', '// @@CYCLE_ENGINE@@', ['src/lib/cycle.js'])
build('hera-nudge', '// @@SHARED@@', ['src/lib/cycle.js', 'src/lib/nudges.js'])
