// Builds backend/hera-chat.ts (the single file pasted into Supabase)
// from the template plus Hera's cycle engine, so the app and function share one engine.
import { readFileSync, writeFileSync } from 'node:fs'

const template = readFileSync('backend/hera-chat.template.ts', 'utf8')
const engine = readFileSync('src/lib/cycle.js', 'utf8')
  .replace(/^export /gm, '')
  .replace(/^\/\/.*\n/gm, '')

const out = '// @ts-nocheck\n' + template
  .replace('// GENERATED FILE SOURCE: edit backend/hera-chat.template.ts, then run `npm run build:function`.\n',
           '// Built from backend/hera-chat.template.ts. Do not edit this file directly.\n')
  .replace('// @@CYCLE_ENGINE@@', `// ---- Cycle engine (copied from src/lib/cycle.js) ----\n${engine}`)

writeFileSync('backend/hera-chat.ts', out)
console.log(`backend/hera-chat.ts written (${out.split('\n').length} lines)`)
